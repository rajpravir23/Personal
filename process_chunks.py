import json
import time
import sqlite3
import os
import urllib.request
import urllib.error
from pathlib import Path
from datetime import datetime


# ============================================================
# CONFIGURATION
# ============================================================

BASE_DIR = Path.home() / "UdemyNoteTaker"
ENGINE_DIR = BASE_DIR / "note_engine"
DB_PATH = ENGINE_DIR / "course_ledger.sqlite3"
OUTPUT_DIR = ENGINE_DIR / "outputs"

COURSE_ID = "prompt_engineering"

OLLAMA_URL = "http://localhost:11434/api/chat"
MODEL = "qwen2.5:3b"

MAX_ATTEMPTS = 3
RETRY_DELAY_SECONDS = 5
REQUEST_TIMEOUT_SECONDS = 600


# ============================================================
# DATABASE
# ============================================================

def get_pending_chunks():
    """Get pending or retryable chunks for this course."""

    with sqlite3.connect(DB_PATH) as conn:
        conn.row_factory = sqlite3.Row

        rows = conn.execute(
            """
            SELECT *
            FROM chunks
            WHERE course_id = ?
              AND status IN ('pending', 'failed')
              AND attempts < ?
            ORDER BY source_file, chunk_index
            """,
            (COURSE_ID, MAX_ATTEMPTS),
        ).fetchall()

    return [dict(row) for row in rows]


def update_chunk_status(
    chunk_id,
    status,
    attempts=None,
    error_message=None,
    notes_path=None,
):
    """Persist the chunk's processing status."""

    with sqlite3.connect(DB_PATH) as conn:
        conn.execute(
            """
            UPDATE chunks
            SET status = ?,
                attempts = COALESCE(?, attempts),
                error_message = ?,
                notes_path = COALESCE(?, notes_path),
                updated_at = CURRENT_TIMESTAMP
            WHERE chunk_id = ?
            """,
            (
                status,
                attempts,
                error_message,
                notes_path,
                chunk_id,
            ),
        )


# ============================================================
# READ CHUNK JSON
# ============================================================

def read_chunk_transcript(chunk):
    """Read the JSON file generated by the transcript importer."""

    chunk_folder = ENGINE_DIR / "courses" / COURSE_ID

    # The importer uses one-based filename numbering.
    chunk_number = int(chunk["chunk_index"]) + 1

    chunk_file = (
        chunk_folder
        / f"{Path(chunk['source_file']).stem}"
          f"_chunk_{chunk_number:04d}.json"
    )

    if not chunk_file.exists():
        raise FileNotFoundError(
            f"Chunk JSON was not found: {chunk_file}"
        )

    with chunk_file.open("r", encoding="utf-8") as file:
        data = json.load(file)

    transcript = (
        data.get("transcript_text")
        or data.get("text")
        or data.get("transcript")
        or ""
    ).strip()

    if not transcript:
        raise ValueError(
            f"Transcript is empty in {chunk_file}. "
            f"Available fields: {list(data.keys())}"
        )

    return transcript, chunk_file


# ============================================================
# PROMPT
# ============================================================

def build_prompt(chunk, transcript):
    return f"""
You are an expert instructor and detailed technical note-taker.

Create thorough, accurate study notes from the transcript below.
Explain unfamiliar ideas for a beginner.

SOURCE INFORMATION
Course: {chunk['course_id']}
Lecture: {chunk['lecture_name']}
Source file: {chunk['source_file']}
Chunk index: {chunk['chunk_index']}
Start: {chunk['start_seconds']} seconds
End: {chunk['end_seconds']} seconds

IMPORTANT RULES
- Preserve the lecturer's meaning.
- Cover every distinct concept and important detail present.
- Do not invent statements, examples, statistics, or timestamps.
- Explain definitions and terminology in plain language.
- Capture procedures as numbered steps.
- Include examples, code, formulas, and comparisons when present.
- Explain relevant limitations and common mistakes.
- Clearly label useful extra context as "Supplementary explanation".
- Mark unclear or possibly mistranscribed statements as uncertain.
- If a topic is incomplete, mention that it may continue later.
- Use timestamps from the transcript when available.
- Do not claim perfect coverage; identify what was actually covered.

OUTPUT FORMAT

# Lecture Notes

## 1. Overview
## 2. Learning Objectives
## 3. Detailed Notes
## 4. Key Terms and Definitions
## 5. Examples and Walkthroughs
## 6. Procedures and Workflows
## 7. Limitations and Common Mistakes
## 8. Practical Applications
## 9. Interview Questions and Model Answers
## 10. Recall Questions
## 11. Coverage Checklist
## 12. Unclear or Potentially Missing Information
## 13. Chunk Handoff Notes

SOURCE TRANSCRIPT
=================
{transcript}
"""


# ============================================================
# OLLAMA API
# ============================================================

def generate_notes(chunk, transcript):
    """Generate notes locally using the Ollama chat API."""

    payload = {
        "model": MODEL,
        "stream": False,
        "messages": [
            {
                "role": "system",
                "content": (
                    "Produce comprehensive Markdown study notes. "
                    "Stay faithful to the transcript. Distinguish "
                    "source content from supplementary explanations."
                ),
            },
            {
                "role": "user",
                "content": build_prompt(chunk, transcript),
            },
        ],
        "options": {
            "temperature": 0.2,
            "num_ctx": 8192,
        },
    }

    request = urllib.request.Request(
        OLLAMA_URL,
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="POST",
    )

    try:
        with urllib.request.urlopen(
            request,
            timeout=REQUEST_TIMEOUT_SECONDS,
        ) as response:
            result = json.loads(
                response.read().decode("utf-8")
            )

    except urllib.error.URLError as error:
        raise RuntimeError(
            "Could not reach Ollama. Check that Ollama is running "
            "and that the model is installed."
        ) from error

    notes = result.get("message", {}).get("content", "").strip()

    if not notes:
        raise RuntimeError(
            f"Ollama returned no note text. Response: {result}"
        )

    return notes


# ============================================================
# PROCESS A CHUNK
# ============================================================

def process_chunk(chunk):
    chunk_id = chunk["chunk_id"]
    attempts_already_used = int(chunk["attempts"])

    for attempt in range(
        attempts_already_used + 1,
        MAX_ATTEMPTS + 1,
    ):
        try:
            update_chunk_status(
                chunk_id,
                status="processing",
                attempts=attempt,
                error_message=None,
            )

            transcript, chunk_file = read_chunk_transcript(chunk)

            print(f"Generating notes with {MODEL}...")
            notes = generate_notes(chunk, transcript)

            output_folder = OUTPUT_DIR / COURSE_ID
            output_folder.mkdir(parents=True, exist_ok=True)

            output_file = output_folder / f"{chunk_id}_notes.md"
            temp_file = output_file.with_suffix(".tmp")

            metadata = f"""<!--
Course ID: {COURSE_ID}
Lecture: {chunk['lecture_name']}
Source: {chunk['source_file']}
Chunk index: {chunk['chunk_index']}
Start: {chunk['start_seconds']} seconds
End: {chunk['end_seconds']} seconds
Chunk JSON: {chunk_file}
Model: {MODEL} (local Ollama)
Generated: {datetime.now().isoformat(timespec='seconds')}
-->

"""

            with temp_file.open("w", encoding="utf-8") as file:
                file.write(metadata)
                file.write(notes)
                file.flush()
                os.fsync(file.fileno())

            # Replace the final file only after writing succeeds.
            temp_file.replace(output_file)

            update_chunk_status(
                chunk_id,
                status="completed",
                attempts=attempt,
                error_message=None,
                notes_path=str(output_file),
            )

            print(f"COMPLETED: {chunk_id}")
            print(f"Notes saved: {output_file}")
            return True

        except Exception as error:
            message = f"{type(error).__name__}: {error}"

            update_chunk_status(
                chunk_id,
                status="failed",
                attempts=attempt,
                error_message=message[:2000],
            )

            print(
                f"Attempt {attempt}/{MAX_ATTEMPTS} failed: "
                f"{message}"
            )

            if attempt < MAX_ATTEMPTS:
                wait_seconds = RETRY_DELAY_SECONDS * attempt
                print(f"Retrying in {wait_seconds} seconds...")
                time.sleep(wait_seconds)

    print(f"FAILED AFTER RETRIES: {chunk_id}")
    return False


# ============================================================
# MAIN
# ============================================================

def main():
    if not DB_PATH.exists():
        raise FileNotFoundError(f"Database not found: {DB_PATH}")

    pending = get_pending_chunks()

    if not pending:
        print("No pending or retryable chunks found.")
        print(
            "Check the SQLite status if a chunk has already "
            "used all its attempts."
        )
        return

    print(f"Course: {COURSE_ID}")
    print(f"Chunks to process: {len(pending)}")
    print(f"Local model: {MODEL}")
    print("No OpenAI API calls will be made.")
    print("-" * 60)

    completed = 0
    failed = 0

    for chunk in pending:
        print(
            f"\nProcessing {chunk['lecture_name']} "
            f"| chunk {chunk['chunk_index']} "
            f"| {chunk['start_seconds']}–"
            f"{chunk['end_seconds']} sec"
        )

        if process_chunk(chunk):
            completed += 1
        else:
            failed += 1

    print("\n" + "=" * 60)
    print("PROCESSING SUMMARY")
    print(f"Completed this run: {completed}")
    print(f"Failed this run: {failed}")
    print(f"Attempted chunks: {len(pending)}")


if __name__ == "__main__":
    main()
